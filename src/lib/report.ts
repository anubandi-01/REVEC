import type { AnalysisResult } from "./analysis-core";

export function buildMarkdown(filename: string, r: AnalysisResult) {
  const L: string[] = [];
  L.push(`# Revec.ai feedback report`, ``, `Source file: ${filename}  `, `Generated: ${new Date(r.generated_at).toLocaleString()}`, ``);
  L.push(`## Summary`, ``, r.summary, ``);
  L.push(`## Sentiment (${r.total} responses)`, ``, `| Sentiment | Responses | Share |`, `|---|---|---|`);
  (["positive", "neutral", "negative"] as const).forEach((s) =>
    L.push(`| ${s} | ${r.sentiment.counts[s]} | ${r.sentiment.percents[s]}% |`),
  );
  if (r.average_rating !== null) L.push(``, `Average rating: ${r.average_rating}`);
  L.push(``, `## Recommendations`, ``);
  r.recommendations.forEach((rec, i) => {
    L.push(`### ${i + 1}. ${rec.title} (${rec.priority} priority)`, ``, `Observed: ${rec.rationale}`, ``, ...(rec.hypothesis ? [`Possible cause (hypothesis, unverified): ${rec.hypothesis}`, ``] : []), `Supported by ${rec.supporting_rows} responses. Themes: ${rec.themes.join(", ") || "—"}`, ``);
    rec.evidence.forEach((e) => L.push(`> "${e.quote}" — ${e.source_id}`, ``));
  });
  L.push(`## Themes`, ``);
  r.themes.forEach((t) => {
    L.push(`### ${t.name} — ${t.count} responses (${t.percent}%)`, ``, t.description, ``);
    t.evidence.forEach((e) => L.push(`> "${e.quote}" — ${e.source_id}`, ``));
  });
  L.push(`## Top keywords`, ``, ...r.keywords.map((k) => `- ${k.term}: ${k.count} responses (${k.percent}%)`), ``);
  const v = r.verification;
  L.push(`## Verification`, ``, `${v.quotes_verified} of ${v.quotes_proposed} proposed quotes matched their source row exactly. ${v.quotes_rejected} were removed. ${v.recommendations_dropped} recommendations without verified evidence were removed. All counts and percentages were calculated from the uploaded rows, not generated by AI.`);
  return L.join("\n");
}

export function download(name: string, content: Blob) {
  const url = URL.createObjectURL(content);
  const inFrame = (() => { try { return window.self !== window.top; } catch { return true; } })();
  if (inFrame) {
    // Embedded previews often block downloads; open the file in a new tab instead.
    const w = window.open(url, "_blank", "noopener");
    if (w) { setTimeout(() => URL.revokeObjectURL(url), 60_000); return; }
  }
  const a = document.createElement("a");
  a.href = url;
  a.download = name;
  a.rel = "noopener";
  a.style.display = "none";
  document.body.appendChild(a);
  a.click();
  a.remove();
  setTimeout(() => URL.revokeObjectURL(url), 60_000);
}

let jspdfMod: Promise<typeof import("jspdf")> | null = null;
export function preloadPdf() {
  jspdfMod ??= import("jspdf");
  return jspdfMod;
}

export async function downloadPdf(filename: string, r: AnalysisResult) {
  const { jsPDF } = await preloadPdf();
  const doc = new jsPDF({ unit: "pt", format: "a4" });
  const W = doc.internal.pageSize.getWidth();
  const H = doc.internal.pageSize.getHeight();
  const M = 48;
  let y = M;
  const ensure = (h: number) => {
    if (y + h > H - M) {
      doc.addPage();
      y = M;
    }
  };
  const text = (s: string, size = 10, style: "normal" | "bold" | "italic" = "normal", color: [number, number, number] = [40, 36, 32]) => {
    doc.setFont("helvetica", style);
    doc.setFontSize(size);
    doc.setTextColor(...color);
    const lines = doc.splitTextToSize(s, W - M * 2);
    lines.forEach((l: string) => {
      ensure(size * 1.4);
      doc.text(l, M, y);
      y += size * 1.4;
    });
  };
  const gap = (n = 10) => (y += n);
  text("Revec.ai — Feedback report", 22, "bold");
  text(`${filename} · ${r.total} responses · ${new Date(r.generated_at).toLocaleDateString()}`, 9, "normal", [120, 110, 100]);
  gap(12);
  text(r.summary, 11);
  gap(14);
  text("Sentiment", 14, "bold");
  (["positive", "neutral", "negative"] as const).forEach((s) =>
    text(`${s.charAt(0).toUpperCase() + s.slice(1)}: ${r.sentiment.counts[s]} (${r.sentiment.percents[s]}%)`, 10),
  );
  if (r.average_rating !== null) text(`Average rating: ${r.average_rating}`, 10);
  gap(14);
  text("Recommendations", 14, "bold");
  r.recommendations.forEach((rec, i) => {
    gap(6);
    text(`${i + 1}. ${rec.title}  [${rec.priority} priority · ${rec.supporting_rows} responses]`, 11, "bold");
    text(`Observed: ${rec.rationale}`, 10);
    if (rec.hypothesis) text(`Possible cause (hypothesis, unverified): ${rec.hypothesis}`, 9, "italic", [110, 100, 90]);
    rec.evidence.forEach((e) => text(`"${e.quote}" — ${e.source_id}`, 9, "italic", [170, 70, 40]));
  });
  gap(14);
  text("Themes", 14, "bold");
  r.themes.forEach((t) => {
    gap(6);
    text(`${t.name} — ${t.count} responses (${t.percent}%)`, 11, "bold");
    text(t.description, 10);
    t.evidence.forEach((e) => text(`"${e.quote}" — ${e.source_id}`, 9, "italic", [170, 70, 40]));
  });
  gap(14);
  text("Top keywords", 14, "bold");
  text(r.keywords.map((k) => `${k.term} (${k.count})`).join(" · "), 10);
  gap(14);
  text("Verification", 14, "bold");
  const v = r.verification;
  text(`${v.quotes_verified} of ${v.quotes_proposed} proposed quotes matched their source row exactly; ${v.quotes_rejected} were removed. ${v.recommendations_dropped} recommendations without verified evidence were removed. All counts and percentages are calculated from the uploaded rows.`, 9);
  doc.save(`revec-report-${filename.replace(/\.[^.]+$/, "")}.pdf`);
}
